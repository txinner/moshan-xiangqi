import assert from 'node:assert/strict';
import {openLocalDatabase} from '../server/node-db.js';
import {RoomService,handleRoomRequest} from '../server/rooms.js';
const db=openLocalDatabase(':memory:'),service=new RoomService(db);
const host=await service.create('white');assert.match(host.code,/^[2-9A-HJ-NP-Z]{8}$/);assert.equal(host.side,'white');assert.equal(host.joined,false);assert.equal(host.token.length,64);
await assert.rejects(()=>service.read(host.code,'x'.repeat(64)),err=>err.status===403);
const guest=await service.join(host.code);assert.equal(guest.side,'black');assert.equal(guest.joined,true);
await assert.rejects(()=>service.join(host.code),err=>err.status===409);
assert.equal(JSON.stringify(await service.read(host.code,host.token)).includes('host_hash'),false);
let snap=await service.read(host.code,host.token);
await assert.rejects(()=>service.action(host.code,guest.token,{action:'move',uci:'b9c7',version:snap.version,round:1}),err=>err.status===409);
await assert.rejects(()=>service.action(host.code,host.token,{action:'move',uci:'b0b2',version:snap.version,round:1}),err=>err.status===400);
snap=await service.action(host.code,host.token,{action:'move',uci:'b0c2',version:snap.version,round:1});assert.equal(snap.game.history.length,1);
await assert.rejects(()=>service.action(host.code,guest.token,{action:'move',uci:'b9c7',version:snap.version-1,round:1}),err=>err.status===409);
snap=await service.action(host.code,guest.token,{action:'move',uci:'b9c7',version:snap.version,round:1});
const race=await Promise.allSettled(['a0a1','c0e2'].map(uci=>service.action(host.code,host.token,{action:'move',uci,version:snap.version,round:1})));
assert.equal(race.filter(result=>result.status==='fulfilled').length,1,'concurrent moves cannot both commit');
snap=await service.action(host.code,guest.token,{action:'resign',round:1});assert.equal(snap.game.ended.winner,'white');
snap=await service.action(host.code,host.token,{action:'rematch',round:1});assert.ok(snap.game.ended);assert.equal(snap.game.ready.length,1);
snap=await service.action(host.code,guest.token,{action:'rematch',round:1});assert.equal(snap.game.round,2);assert.equal(snap.game.hostColor,'black');assert.equal(snap.game.history.length,0);assert.equal(snap.game.ended,null);
await assert.rejects(()=>service.action(host.code,host.token,{action:'rematch',round:1}),err=>err.status===409);
const resumed=await service.read(host.code,guest.token);assert.equal(resumed.side,'white');assert.equal(resumed.game.round,2);
snap=await service.action(host.code,host.token,{action:'leave',round:2});assert.equal(snap.closed,true);assert.equal(snap.game.ended.winner,'white');
await assert.rejects(()=>service.action(host.code,guest.token,{action:'move',round:2}),err=>err.status===410);
const cors=await handleRoomRequest(new Request('https://example.com/api/rooms',{method:'OPTIONS',headers:{Origin:'http://127.0.0.1:18765'}}),db);assert.equal(cors.status,204);assert.equal(cors.headers.get('Access-Control-Allow-Origin'),'http://127.0.0.1:18765');
const forged=await handleRoomRequest(new Request('https://example.com/api/rooms',{method:'POST',headers:{Origin:'https://unrelated.test'},body:'{}'}),db);assert.equal(forged.status,403);
const malformed=await handleRoomRequest(new Request('https://example.com/api/rooms',{method:'POST',body:'null'}),db);assert.equal(malformed.status,400);
const h2=await service.create('white');
await assert.rejects(()=>service.action(h2.code,h2.token,{action:'swap-request',round:1,version:0}),e=>e.status===409);
const g2=await service.join(h2.code);
let state=await service.read(h2.code,h2.token);
const act=async(who,action,extra={})=>state=await service.action(h2.code,who.token,{action,round:1,version:state.version,...extra});
await act(h2,'move',{uci:'b0c2'});
const fen=state.game.fen,records=JSON.stringify(state.game.history),startedAt=state.game.startedAt;
await act(h2,'swap-request');let requestId=state.game.swapRequest.id;
assert.equal(state.game.hostColor,'white','request alone cannot swap seats');
await assert.rejects(()=>act(h2,'swap-accept',{requestId}),e=>e.status===403);
await assert.rejects(()=>act(g2,'swap-cancel',{requestId}),e=>e.status===403);
await act(g2,'swap-decline',{requestId});assert.equal(state.game.hostColor,'white');
await act(h2,'swap-request');requestId=state.game.swapRequest.id;
await act(h2,'swap-cancel',{requestId});assert.equal(state.game.swapRequest,null);
await act(h2,'swap-request');requestId=state.game.swapRequest.id;
await act(g2,'swap-accept',{requestId});
assert.equal(state.game.hostColor,'black');assert.equal(state.side,'white');
assert.equal(state.game.fen,fen);assert.equal(JSON.stringify(state.game.history),records);assert.equal(state.game.startedAt,startedAt);
assert.equal((await service.read(h2.code,h2.token)).side,'black');
await assert.rejects(()=>act(g2,'swap-accept',{requestId}),e=>e.status===409);
await assert.rejects(()=>act(g2,'move',{uci:'b9c7'}),e=>e.status===409);
await act(h2,'swap-request');requestId=state.game.swapRequest.id;
await act(h2,'move',{uci:'b9c7'});assert.equal(state.game.swapRequest,null);
await assert.rejects(()=>act(g2,'swap-accept',{requestId}),e=>e.status===409);
await act(g2,'swap-request');requestId=state.game.swapRequest.id;
await act(h2,'swap-accept',{requestId});assert.equal(state.game.hostColor,'white');
await act(h2,'resign');
await assert.rejects(()=>act(g2,'swap-request'),e=>e.status===409);
db.close();console.log('PASS: room lifecycle, legal play, concurrency, rematch, swap consent/rejection/cancellation, control transfer, stale request invalidation, unchanged position/history/timer, ended-game guard, CORS.');
